// textarea/input のユーザー入力値、option.value、data-* などは触らない。
// 表示文字・title・aria-label・placeholder のみ変える。
function translateString(value: string): string {
  if (!value) return value;

  const trimmed = value.trim();
  if (!trimmed) return value;

  const exact = EXACT[trimmed];
  if (exact !== undefined) {
    const start = value.indexOf(trimmed);
    return value.slice(0, start) + exact + value.slice(start + trimmed.length);
  }

  let out = value;
  for (const [ko, ja] of PARTIAL) {
    out = out.split(ko).join(ja);
  }

  // 動的な短い表記
  out = out.replace(/(\d+)명 지원/g, '$1名対応');
  out = out.replace(/(\d+)명 적용/g, '$1名適用');
  out = out.replace(/(\d+)명을 불러왔습니다/g, '$1名を読み込みました');
  out = out.replace(/미지원 (\d+)명 제외/g, '未対応$1名を除外');
  out = out.replace(/(\d+)덱/g, '$1編成');
  out = out.replace(/(\d+)개/g, '$1個');
  out = out.replace(/(\d+)회 발동/g, '$1回発動');
  out = out.replace(/(\d+)위/g, '$1位');
  out = out.replace(/(\d+(?:\.\d+)?)% 기여/g, '貢献 $1%');
  out = out.replace(/(\d+(?:\.\d+)?)배/g, '$1倍');
  out = out.replace(/(\d+)초/g, '$1秒');
  out = out.replace(/(\d+)레벨/g, 'Lv$1');

  return out;
}

function translateElement(el: Element): void {
  // 表示用属性だけ。
  for (const attr of ['title', 'aria-label', 'placeholder']) {
    const current = el.getAttribute(attr);
    if (!current) continue;
    const next = translateString(current);
    if (next !== current) el.setAttribute(attr, next);
  }

  // button/submit/reset input の表示値のみ。
  // text/search/number 等のユーザー入力 value は絶対に変えない。
  if (
    el instanceof HTMLInputElement
    && ['button', 'submit', 'reset'].includes(el.type)
  ) {
    const next = translateString(el.value);
    if (next !== el.value) el.value = next;
  }
}

function translateNode(node: Node): void {
  if (node.nodeType === Node.TEXT_NODE) {
    const parent = node.parentElement;
    if (!parent) return;

    // コード・入力欄等は対象外。
    if (parent.closest('script,style,pre,code,textarea')) return;

    const current = node.nodeValue ?? '';
    const next = translateString(current);
    if (next !== current) node.nodeValue = next;
    return;
  }

  if (!(node instanceof Element)) return;
  if (node.matches('script,style,pre,code,textarea')) return;

  translateElement(node);
  for (const child of node.childNodes) {
    translateNode(child);
  }
}

/**
 * 日本語表示を有効化する。
 *
 * MutationObserver を使う理由:
 * 計算結果、モーダル、Blabla同期結果、タイムライン等は
 * 最初の画面表示後に動的生成されるため。
 */
export function installJapaneseUi(
  root: HTMLElement = document.body,
): () => void {
  document.documentElement.lang = 'ja';

  translateNode(root);

  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === 'characterData') {
        translateNode(record.target);
        continue;
      }

      for (const node of record.addedNodes) {
        translateNode(node);
      }

      if (record.target instanceof Element) {
        translateElement(record.target);
      }
    }
  });

  observer.observe(root, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ['title', 'aria-label', 'placeholder'],
  });

  return () => observer.disconnect();
}
